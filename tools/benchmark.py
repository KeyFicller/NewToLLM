"""Speed comparison: PyTorch vs LibTorch ToyModel (forward / train step).

Same config (configs/toy_gpt2.json), same seed, same batch/tokens, same
thread count on both sides. CPU only for now.

    python tools/benchmark.py                       # small model
    python tools/benchmark.py --full --write        # GPT-2 124M shape, save docs/benchmark.md
"""

import argparse
import json
import platform
import subprocess
import sys
import time
from datetime import datetime
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT))

import torch  # noqa: E402

from python_impl.toy_model.model import ToyModel  # noqa: E402
from python_impl.utils import runtime  # noqa: E402

DEFAULT_EXE = REPO_ROOT / "build" / "cpp_impl" / "tools" / "benchmark"


def time_ms(fn, warmup, iters):
    for _ in range(warmup):
        fn()
    t0 = time.perf_counter()
    for _ in range(iters):
        fn()
    return (time.perf_counter() - t0) * 1000.0 / iters


def bench_python(full, batch, tokens, iters, warmup):
    runtime.set_options(small=not full)
    cfg = runtime.model_config()
    torch.manual_seed(runtime.seed())
    model = ToyModel(cfg)
    inp = torch.randint(0, cfg["vocab_size"], (batch, tokens))
    tgt = torch.randint(0, cfg["vocab_size"], (batch, tokens))

    model.eval()

    def fwd():
        with torch.no_grad():
            model(inp)

    fwd_ms = time_ms(fwd, warmup, iters)

    model.train()
    opt = torch.optim.AdamW(model.parameters(), lr=4e-4, weight_decay=0.1)

    def step():
        opt.zero_grad()
        loss = torch.nn.functional.cross_entropy(model(inp).flatten(0, 1), tgt.flatten())
        loss.backward()
        opt.step()

    step_ms = time_ms(step, warmup, iters)
    n = batch * tokens
    return {
        "side": "python", "model": "full" if full else "small", "batch": batch, "tokens": tokens,
        "threads": torch.get_num_threads(), "forward_ms": fwd_ms, "train_step_ms": step_ms,
        "forward_tok_s": n / fwd_ms * 1000, "train_tok_s": n / step_ms * 1000,
    }


def bench_cpp(exe, full, batch, tokens, iters, warmup, threads):
    cmd = [str(exe), "--batch", str(batch), "--tokens", str(tokens), "--iters", str(iters),
           "--warmup", str(warmup), "--threads", str(threads)]
    if full:
        cmd.append("--full")
    out = subprocess.run(cmd, check=True, capture_output=True, text=True).stdout
    return json.loads(out.strip().splitlines()[-1])


def to_markdown(rows, meta):
    lines = [
        "# Benchmark: PyTorch vs LibTorch",
        "",
        f"- date: {meta['date']}",
        f"- machine: {meta['machine']}",
        f"- PyTorch: {meta['torch']} (LibTorch version: see `sandbox verify`)",
        f"- CPU only, threads = {meta['threads']}, iters = {meta['iters']} (warmup {meta['warmup']})",
        "- generated by `python tools/benchmark.py --write`",
        "",
        "| model | side | batch×tokens | forward ms | train step ms | forward tok/s | train tok/s |",
        "|-------|------|--------------|-----------:|--------------:|--------------:|------------:|",
    ]
    for r in rows:
        lines.append(
            f"| {r['model']} | {r['side']} | {r['batch']}×{r['tokens']} | {r['forward_ms']:.1f} | "
            f"{r['train_step_ms']:.1f} | {r['forward_tok_s']:.0f} | {r['train_tok_s']:.0f} |"
        )
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--full", action="store_true", help="also benchmark the GPT-2 124M shape")
    ap.add_argument("--batch", type=int, default=2)
    ap.add_argument("--tokens", type=int, default=128)
    ap.add_argument("--iters", type=int, default=5)
    ap.add_argument("--warmup", type=int, default=2)
    ap.add_argument("--threads", type=int, default=torch.get_num_threads())
    ap.add_argument("--exe", type=Path, default=DEFAULT_EXE)
    ap.add_argument("--write", action="store_true", help="write results to docs/benchmark.md")
    args = ap.parse_args()
    if not args.exe.exists():
        sys.exit(f"[benchmark] C++ executable not found: {args.exe} (build with cmake first)")
    torch.set_num_threads(args.threads)

    rows = []
    for full in ([False, True] if args.full else [False]):
        rows.append(bench_python(full, args.batch, args.tokens, args.iters, args.warmup))
        rows.append(bench_cpp(args.exe, full, args.batch, args.tokens, args.iters, args.warmup, args.threads))
    meta = {
        "date": datetime.now().strftime("%Y-%m-%d"),
        "machine": f"{platform.system()} {platform.machine()}, {platform.processor() or 'cpu'}",
        "torch": torch.__version__, "threads": args.threads, "iters": args.iters, "warmup": args.warmup,
    }
    md = to_markdown(rows, meta)
    print(md)
    if args.write:
        (REPO_ROOT / "docs" / "benchmark.md").write_text(md, encoding="utf-8")
        print("[benchmark] wrote docs/benchmark.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
